const assert = require('assert')
const { filterPlays } = require('../utils/filters')
const plays = require('../data/plays')
const storage = { 'weekend-unboxed-filters-v1': { district: '杨浦', mood: 'thrill' } }
let page
global.wx = { getStorageSync: key => storage[key], setStorageSync: (key, value) => { storage[key] = value }, showShareMenu() {} }
global.getApp = () => ({ getPlays: () => plays, getState: () => ({ challenges: [], tagScores: {}, seenIds: [] }) })
global.Page = config => { page = config }
require('../pages/index/index')
page.setData = data => Object.assign(page.data, data)
page.onLoad()
page.onShow()
assert.deepStrictEqual(page.data.selectedDistricts, ['杨浦'])
assert.deepStrictEqual(page.data.selectedMoods, ['thrill'])
assert.strictEqual(page.data.availableCount, filterPlays(plays, { district: '杨浦', mood: 'thrill' }).length)
page.data.play = plays.find(play => play.recommendable)
page.selectDistrict({ currentTarget: { dataset: { id: '长宁' } } })
assert.strictEqual(page.data.play, null)
assert.deepStrictEqual(storage['weekend-unboxed-filters-v1'].districts, ['杨浦', '长宁'])
assert.deepStrictEqual(page.data.selectedDistricts, ['杨浦', '长宁'])
page.selectMood({ currentTarget: { dataset: { id: 'night' } } })
assert.deepStrictEqual(page.data.selectedMoods, ['thrill', 'night'])
assert.strictEqual(page.data.availableCount, filterPlays(plays, { districts: ['杨浦', '长宁'], moods: ['thrill', 'night'] }).length)
assert.strictEqual(page.data.moodRows.flatMap(row => row.items).filter(item => item.selected).length, 2)
assert.ok(page.data.districtRows.every(row => row.items.length <= 3))
assert.strictEqual(page.data.districtRows.length, 6)
assert.strictEqual(page.data.districtRows.flatMap(row => row.items).length, 17)
page.selectDistrict({ currentTarget: { dataset: { id: '杨浦' } } })
assert.deepStrictEqual(page.data.selectedDistricts, ['长宁'])
page.selectMood({ currentTarget: { dataset: { id: 'thrill' } } })
assert.deepStrictEqual(page.data.selectedMoods, ['night'])
page.selectDistrict({ currentTarget: { dataset: { id: 'all' } } })
assert.deepStrictEqual(page.data.selectedDistricts, [])
assert.strictEqual(page.data.districtLabel, '全上海')
page.selectMood({ currentTarget: { dataset: { id: 'random' } } })
assert.deepStrictEqual(page.data.selectedMoods, [])
page.selectMood({ currentTarget: { dataset: { id: 'night' } } })
page.selectMood({ currentTarget: { dataset: { id: 'night' } } })
assert.deepStrictEqual(page.data.selectedMoods, [])
assert.ok(page.data.moodRows[0].items[0].selected)
page.selectDistrict({ currentTarget: { dataset: { id: '崇明' } } })
page.selectMood({ currentTarget: { dataset: { id: 'thrill' } } })
assert.strictEqual(page.data.availableCount, filterPlays(plays, { district: '崇明', mood: 'thrill' }).length)
// Exercise the empty-state branch with an empty catalog, not a real district we have now populated.
const populatedApp = global.getApp
global.getApp = () => ({ getPlays: () => [], getState: () => ({ challenges: [], tagScores: {}, seenIds: [] }) })
page.onShow()
assert.strictEqual(page.data.availableCount, 0)
assert.ok(page.data.emptyMessage)
page.draw()
assert.strictEqual(page.data.isDrawing, false)
global.getApp = populatedApp
storage['weekend-unboxed-filters-v1'] = { districts: ['杨浦', '长宁'], moods: ['healing', 'arts'] }
page.onLoad()
assert.deepStrictEqual(page.data.selectedDistricts, ['杨浦', '长宁'])
assert.deepStrictEqual(page.data.selectedMoods, ['healing', 'arts'])
assert.strictEqual(page.data.availableCount, filterPlays(plays, storage['weekend-unboxed-filters-v1']).length)
console.log('multi-select toggles, three-column rows, storage migration and empty selection checks passed')
